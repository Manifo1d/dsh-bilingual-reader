/**
 * Build the browser half into the single client.js the DSH module loader
 * expects. React is provided by the page; everything else is bundled.
 */

import { build } from 'esbuild'
import { readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const packageJson = JSON.parse(await readFile(resolve(root, 'package.json'), 'utf8'))

const result = await build({
  entryPoints: [resolve(root, 'src/client/entry.jsx')],
  bundle: true,
  write: false,
  format: 'cjs',
  platform: 'browser',
  target: ['chrome110', 'safari16'],
  external: ['react'],
  jsx: 'transform',
  define: {
    'process.env.NODE_ENV': '"production"',
  },
  legalComments: 'none',
  logLevel: 'warning',
})

const code = result.outputFiles[0].text
const banner = `/* Bilingual documents ${packageJson.version} — generated by scripts/build.mjs; do not edit by hand. */`
const wrapped = `${banner}
window.__ModuleLoader__.load({
  id: ${JSON.stringify(packageJson.name)},
  factory(require) {
    const module = { exports: {} };
    const exports = module.exports;
    (function (module, exports, require) {
${code}
    })(module, exports, require);
    return module.exports;
  },
});
`
await writeFile(resolve(root, 'client.js'), wrapped)
console.log(`client.js written (${(wrapped.length / 1024).toFixed(1)} KiB)`)
